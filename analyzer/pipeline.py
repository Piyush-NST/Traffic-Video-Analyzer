"""Shared frame-by-frame traffic-video processing pipeline."""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import cv2
import matplotlib
import numpy as np
import pandas as pd
import yaml
from tqdm import tqdm

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from .congestion import CongestionDetector
from .counter import LineCounter
from .detector import VehicleDetector
from .speed import SpeedEstimator
from .tracker import TrackedVehicle, VehicleTracker

ProgressCallback = Callable[[int, int], None]


@dataclass(frozen=True)
class AnalysisResult:
    """Artifacts generated by a processing run."""
    video_path: Path
    csv_path: Path
    chart_path: Path
    summary_path: Path
    processed_frames: int
    total_frames: int
    counts: dict[str, dict[str, int]]


def load_config(config_path: str | Path) -> dict:
    """Load required YAML sections and fail clearly for malformed config."""
    path = Path(config_path)
    if not path.is_file():
        raise FileNotFoundError(f"Configuration not found: {path}")
    with path.open(encoding="utf-8") as file:
        config = yaml.safe_load(file)
    required = {"model", "tracker", "counting", "calibration", "congestion", "output", "ui"}
    if not isinstance(config, dict) or required - set(config):
        raise ValueError(f"config must contain: {', '.join(sorted(required))}")
    return config


class TrafficAnalyzer:
    """Detect, track, count, estimate speed, annotate, and report traffic."""
    def __init__(self, config_path: str | Path = "config.yaml", config: dict | None = None) -> None:
        self.config = config if config is not None else load_config(config_path)

    def _draw(self, frame: np.ndarray, vehicles: list[TrackedVehicle], speeds: dict[int, float], counter: LineCounter, occupancy: int, congested: bool) -> np.ndarray:
        output = frame.copy()
        cfg = self.config
        scale, thick = float(cfg["output"]["overlay_font_scale"]), int(cfg["output"]["overlay_thickness"])
        cv2.line(output, tuple(cfg["counting"]["line_start"]), tuple(cfg["counting"]["line_end"]), (0, 255, 255), thick + 1)
        zone = np.asarray(cfg["congestion"]["zone_polygon"], dtype=np.int32)
        cv2.polylines(output, [zone], True, (0, 0, 255) if congested else (255, 128, 0), thick)
        for vehicle in vehicles:
            x1, y1, x2, y2 = map(int, vehicle.xyxy)
            color = (0, 0, 255) if congested else (0, 220, 0)
            cv2.rectangle(output, (x1, y1), (x2, y2), color, thick)
            cv2.putText(output, f"{vehicle.class_name} #{vehicle.track_id}  {speeds[vehicle.track_id]:.1f} km/h", (x1, max(20, y1 - 8)), cv2.FONT_HERSHEY_SIMPLEX, scale, color, thick, cv2.LINE_AA)
        totals = counter.totals()
        cv2.rectangle(output, (10, 10), (370, 92 + 24 * sum(len(x) for x in totals.values())), (20, 20, 20), -1)
        status_color = (0, 80, 255) if congested else (0, 255, 0)
        cv2.putText(output, f"Zone: {occupancy}/{cfg['congestion']['vehicle_threshold']}  {'CONGESTED' if congested else 'CLEAR'}", (18, 35), cv2.FONT_HERSHEY_SIMPLEX, scale, status_color, thick, cv2.LINE_AA)
        y = 60
        for direction in ("in", "out"):
            values = ", ".join(f"{name} {number}" for name, number in sorted(totals.get(direction, {}).items())) or "0"
            cv2.putText(output, f"{direction.upper()}: {values}", (18, y), cv2.FONT_HERSHEY_SIMPLEX, scale, (255, 255, 255), thick, cv2.LINE_AA)
            y += 24
        return output

    @staticmethod
    def _chart(events: list[dict], path: Path) -> None:
        """Write a two-panel analytics report."""
        path.parent.mkdir(parents=True, exist_ok=True)
        figure, axes = plt.subplots(1, 2, figsize=(12, 4.5))
        data = pd.DataFrame(events)
        if data.empty:
            for axis in axes:
                axis.text(.5, .5, "No line crossings recorded", ha="center", va="center")
                axis.set_axis_off()
        else:
            data["minute"] = (data.timestamp.astype(float) // 60).astype(int)
            data.groupby("minute").size().plot.bar(ax=axes[0], color="#1976d2", title="Vehicles per minute")
            axes[0].set(xlabel="Minute", ylabel="Vehicles")
            data["class"].value_counts().plot.bar(ax=axes[1], color="#43a047", title="Crossings by class")
            axes[1].set(xlabel="Class", ylabel="Vehicles")
        figure.tight_layout()
        figure.savefig(path, dpi=150)
        plt.close(figure)

    def _reencode(self, temporary: Path, final: Path) -> Path:
        config = self.config["output"]
        ffmpeg = shutil.which(str(config["ffmpeg_binary"]))
        if bool(config["reencode_h264"]) and ffmpeg:
            proc = subprocess.run([ffmpeg, "-y", "-i", str(temporary), "-c:v", "libx264", "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(final)], capture_output=True, text=True, check=False)
            if proc.returncode == 0 and final.exists() and final.stat().st_size:
                temporary.unlink(missing_ok=True)
                return final
        temporary.replace(final)
        return final

    def process(self, input_path: str | Path, output_path: str | Path, progress_callback: ProgressCallback | None = None) -> AnalysisResult:
        """Run the complete processing loop and export all report artifacts."""
        source, output = Path(input_path), Path(output_path)
        if not source.is_file() or not source.stat().st_size:
            raise FileNotFoundError(f"Input video not found or empty: {source}")
        capture = cv2.VideoCapture(str(source))
        if not capture.isOpened():
            raise ValueError(f"Cannot read video (it may be corrupt): {source}")
        fps = float(capture.get(cv2.CAP_PROP_FPS))
        width, height, total = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH)), int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT)), int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
        if fps <= 0 or width <= 0 or height <= 0:
            capture.release()
            raise ValueError("video metadata is invalid or unreadable")
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary = output.with_name(f"{output.stem}.temporary.mp4")
        codec = str(self.config["output"]["codec"])
        if len(codec) != 4:
            raise ValueError("output.codec must be exactly four characters")
        try:
            detector = VehicleDetector(self.config["model"]["weights"], float(self.config["model"]["confidence_threshold"]), float(self.config["model"]["iou_threshold"]), self.config["model"]["vehicle_classes"])
            tracker = VehicleTracker(fps, self.config["tracker"])
            counter = LineCounter(self.config["counting"]["line_start"], self.config["counting"]["line_end"], self.config["counting"]["in_direction"], float(self.config["counting"]["min_crossing_distance_px"]))
            speed = SpeedEstimator(fps, **self.config["calibration"])
            congestion = CongestionDetector(self.config["congestion"]["zone_polygon"], int(self.config["congestion"]["vehicle_threshold"]))
        except Exception:
            capture.release()
            raise
        writer = cv2.VideoWriter(str(temporary), cv2.VideoWriter_fourcc(*codec), fps, (width, height))
        if not writer.isOpened():
            capture.release()
            raise RuntimeError("could not create output video writer")
        events: list[dict] = []
        processed, limit = 0, int(self.config["output"].get("max_frames", 0))
        work_total = min(total, limit) if limit else total
        try:
            with tqdm(total=work_total, desc="Analyzing", unit="frame", disable=progress_callback is not None) as bar:
                while not limit or processed < limit:
                    ok, frame = capture.read()
                    if not ok:
                        break
                    vehicles = tracker.update(detector.detect(frame))
                    speeds = {vehicle.track_id: speed.update(vehicle.track_id, vehicle.centroid) for vehicle in vehicles}
                    new_events = {event.track_id: event for event in counter.update(vehicles)}
                    for vehicle in vehicles:
                        event = new_events.get(vehicle.track_id)
                        if event:
                            events.append({"timestamp": round(processed / fps, 3), "vehicle_id": event.track_id, "class": event.class_name, "speed_kmh": round(speeds[vehicle.track_id], 2), "direction": event.direction})
                    occupancy, is_congested = congestion.check(vehicles)
                    writer.write(self._draw(frame, vehicles, speeds, counter, occupancy, is_congested))
                    processed += 1
                    bar.update(1)
                    if progress_callback:
                        progress_callback(processed, work_total)
        finally:
            capture.release()
            writer.release()
        video_path = self._reencode(temporary, output)
        csv_path, chart_path = output.with_suffix(".csv"), output.with_name(f"{output.stem}_summary.png")
        summary_path = output.with_name(f"{output.stem}_summary.json")
        pd.DataFrame(events, columns=["timestamp", "vehicle_id", "class", "speed_kmh", "direction"]).to_csv(csv_path, index=False)
        self._chart(events, chart_path)
        summary_path.write_text(json.dumps({"input": str(source), "processed_frames": processed, "total_frames": total, "counts": counter.totals(), "crossing_events": len(events)}, indent=2), encoding="utf-8")
        return AnalysisResult(video_path, csv_path, chart_path, summary_path, processed, total, counter.totals())
